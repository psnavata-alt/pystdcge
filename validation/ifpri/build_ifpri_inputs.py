"""IFPRI validation, route A, step 2: inputs for IFPRI's own GAMS model on the condensed Philippine SAM.

Writes, into validation/ifpri/gams_ph/:
  ph_data.gms        sets and parameters in GAMS syntax (run once with GAMS to make ph.gdx, which the data file loads)
  sam_netted.csv     the condensed SAM after IFPRI's netting rules (used by BOTH models, so they see identical data)
and copies IFPRI's include files from external/IFPRI_model-main/ (GNU GPL v2; changed copies are marked).

Like-for-like choices (each documented in validation/ifpri/README.md):
  - IFPRI's netting rules (institution-RoW, factor-RoW, government-household/enterprise transfers) are applied to
    the condensed SAM here, and pystdcge is rerun on the netted SAM;
  - the single margin account 'trc' is split for IFPRI into domestic and import margins in proportion to each good's
    domestic sales and imports (IFPRI charges margins separately; pystdcge charges them on composite supply);
  - one trading region (ROW), no factor nests, one government function, Leontief top-level technology;
  - household demand: LES with all expenditure elasticities 1 and Frisch -1, which is exactly Cobb-Douglas;
  - elasticities as pystdcge: value added 0.8, Armington 2.0, CET 2.0;
  - factor quantities = SAM values (all factor prices 1 in the base), as in pystdcge.
Run:  py validation/ifpri/build_ifpri_inputs.py
"""
from __future__ import annotations

import shutil
from pathlib import Path

import numpy as np
import pandas as pd

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
OUT = HERE / "gams_ph"
OUT.mkdir(exist_ok=True)
SRC = ROOT / "external" / "IFPRI_model-main" / "src" / "gams" / "algebraic"

sam = pd.read_csv(HERE / "out" / "sam2023_condensed_9sectors.csv", index_col=0)
codes = list(sam.index)
A = [c for c in codes if c.startswith("a")]
C = [c for c in codes if c.startswith("c")]
F = ["flab-n", "flab-p", "flab-s", "flnd", "fcap"]
H = [c for c in codes if c.startswith("hhd")]
INSD = ["ent"] + H + ["gov"]
INSDNG = ["ent"] + H

# ---- IFPRI's netting rules (1dmodel.gms, section 2, 'SAM adjustments'), applied to the SAM both models use
t = sam.copy()
for i in INSD:
    t.loc[i, "row"] -= t.loc["row", i]; t.loc["row", i] = 0.0
for f in F:
    t.loc["row", f] -= t.loc[f, "row"]; t.loc[f, "row"] = 0.0
for i in INSDNG:
    t.loc[i, "gov"] -= t.loc["gov", i]; t.loc["gov", i] = 0.0
for k in codes:
    t.loc[k, k] = 0.0
gap = (t.sum(axis=1) - t.sum(axis=0)).abs().max()
assert gap < 1e-6, gap
t.to_csv(OUT / "sam_netted.csv")

# ---- IFPRI layout: split margins into domestic (trcdom) and import (trcimp) accounts
s = t.copy()
out_val = s.loc[A, C].sum()
dom = (out_val - s.loc[C, "row"]).clip(lower=0)
imp = s.loc["row", C]
share_d = (dom / (dom + imp)).fillna(1.0)
s["trcdom"] = 0.0; s["trcimp"] = 0.0
s.loc["trcdom"] = 0.0; s.loc["trcimp"] = 0.0
s.loc["trcdom", C] = s.loc["trc", C] * share_d
s.loc["trcimp", C] = s.loc["trc", C] * (1 - share_d)
supp = s.loc[C, "trc"]
s.loc[C, "trcdom"] = supp * s.loc["trcdom", C].sum() / supp.sum()
s.loc[C, "trcimp"] = supp * s.loc["trcimp", C].sum() / supp.sum()
s = s.drop(index="trc", columns="trc")
gap = (s.sum(axis=1) - s.sum(axis=0)).abs().max()
assert gap < 1e-6, gap
AC = list(s.index)

pop = pd.read_csv(ROOT / "data" / "raw" / "sam" / "003_IFPRI_SAM_PHL_2023_POP.csv", encoding="utf-8-sig", skiprows=1)
pop.columns = ["name", "code", "num", "shr"][: len(pop.columns)]
popmap = {}
for _, r in pop.iterrows():
    c = str(r["code"]).lower()
    for a, full in (("r", "rur"), ("u", "urb")):
        for q in range(1, 6):
            if c in (f"h_{full}{q}", f"hhd-{a}{q}"):
                popmap[f"hhd-{a}{q}"] = float(str(r["num"]).replace(",", ""))
assert len(popmap) == 10, popmap

# IFPRI's standard account names used by its diagnostics and reports (no flows in this SAM)
IFPRI_LABELS = ['instax', 'factax', 'imptax', 'exptax', 'vatax', 'acttax', 'comtax', 'trncstdom', 'trncstexp', 'trncstimp', 'dum']
q = lambda x: "'" + x + "'"
L = lambda xs: ", ".join(q(x) for x in xs)
lines = ["$ontext", "Philippine data for IFPRI's model (pystdcge validation, route A). Generated by build_ifpri_inputs.py.",
         "Condensed IFPRI 2023 Philippine SAM (9 sectors, 10 households), with IFPRI's netting rules applied. Pesos bn.", "$offtext",
         "$onempty",
         f"SET AC / {L(AC + IFPRI_LABELS + ['total'])} /;",
         f"SET A(AC) / {L(A)} /;", f"SET AAG(AC) / {L(A)} /;", f"SET C(AC) / {L(C)} /;",
         f"SET MAPAAGA(AAG,A) / {', '.join(q(a) + '.' + q(a) for a in A)} /;",
         f"SET MAPA2C(A,C) / {', '.join(q(a) + '.' + q('c' + a[1:]) for a in A)} /;",
         "SET AAGR(A) / 'aagri' /; SET AMIN(A) / 'amine' /;",
         "SET AIND(A) / 'afood', 'aoman', 'achem', 'autil', 'acons' /; SET ASER(A) / 'atrad', 'aserv' /;",
         "SET CAGR(C) / 'cagri' /; SET CMIN(C) / 'cmine' /;",
         "SET CIND(C) / 'cfood', 'coman', 'cchem', 'cutil', 'ccons' /; SET CSER(C) / 'ctrad', 'cserv' /;",
         f"SET F(AC) / {L(F)} /; SET FAGG(F) / /; SET FLAB(F) / 'flab-n', 'flab-p', 'flab-s' /;",
         "SET FCAP(F) / 'fcap' /; SET FLND(F) / 'flnd' /;",
         f"SET INS(AC) / {L(INSD + ['row'])} /; SET INSD(AC) / {L(INSD)} /; SET INSDNG(AC) / {L(INSDNG)} /;",
         "SET EN(AC) / 'ent' /;", f"SET H(AC) / {L(H)} /;",
         f"SET HURB(AC) / {L([h for h in H if '-u' in h])} /; SET HRUR(AC) / {L([h for h in H if '-r' in h])} /;",
         "SET CTD(AC) / 'trcdom' /; SET CTE(AC) / /; SET CTM(AC) / 'trcimp' /;",
         "SET R(AC) / 'row' /;", "SET GOVF / 'gfun' /;",
         "SET TRDELAS / SIGMAQ, SIGMAT, REGIMP, REGEXP /; SET PRDELAS / PRODELAS, PRODELAS2 /;",
         "PARAMETER NEST(F,F) / /;",
         "PARAMETER SAM(AC,AC) /"]
for i in AC:
    for j in AC:
        v = float(s.loc[i, j])
        if abs(v) > 1e-12:
            lines.append(f"  {q(i)}.{q(j)} {v:.10g}")
lines += ["/;",
          "PARAMETER TRADELAS(AC,TRDELAS) / " + ", ".join(f"{q(c)}.SIGMAQ 2.0, {q(c)}.SIGMAT 2.0" for c in C) + " /;",
          "PARAMETER PRODELASTAB(A,PRDELAS) / " + ", ".join(f"{q(a)}.PRODELAS 0.8, {q(a)}.PRODELAS2 0.6" for a in A) + " /;",
          "PARAMETER LESELAS1(H,C) / " + ", ".join(f"{q(h)}.{q(c)} 1" for h in H for c in C if s.loc[c, h] > 0) + " /;",
          "PARAMETER QFINPUT(F,AAG) / /; PARAMETER WFINPUT(F,AAG) / /;",
          "PARAMETER REGIMP(C,R) / " + ", ".join(f"{q(c)}.'row' 100" for c in C) + " /;",
          "PARAMETER REGTAR(C,R) / " + ", ".join(f"{q(c)}.'row' 100" for c in C) + " /;",
          "PARAMETER REGEXP(C,R) / " + ", ".join(f"{q(c)}.'row' 100" for c in C) + " /;",
          "PARAMETER REGETX(C,R) / " + ", ".join(f"{q(c)}.'row' 100" for c in C) + " /;",
          "PARAMETER POPTAB(AC,*) / " + ", ".join(f"{q(h)}.SURVEY {popmap[h]:.6g}" for h in H) + " /;",
          "PARAMETER GOVFSHR2(GOVF,*) / 'gfun'.'GOV' 1 /;",
          "execute_unload 'ph.gdx';"]
(OUT / "ph_data.gms").write_text("\n".join(lines) + "\n", encoding="utf-8")

for f in ("1diagnostics.inc", "1varinit.inc", "1varlow.inc", "1repbase.inc"):
    shutil.copy(SRC / f, OUT / f)
print(f"Wrote {OUT / 'ph_data.gms'} ({len(AC)} accounts) and sam_netted.csv; copied IFPRI include files.")
