"""IFPRI validation with HOME CONSUMPTION kept (book eq. 18 and 34; 8 Oct 2026).

The route-A validation (../ifpri/) moved home consumption to the market before both models ran, because pystdcge could
not do otherwise. pystdcge now has CGE(home="separate"), IFPRI's treatment. This script builds the inputs for running
IFPRI's own model and pystdcge on the same condensed SAM WITH the activity -> household (home consumption) cells kept:

  gams_ph/sam_netted_home.csv   the condensed 2023 SAM (9 sectors, 10 households), home consumption kept, IFPRI netting
  gams_ph/ph_data.gms           the same in GAMS syntax for IFPRI's model (run it once with GAMS to make ph.gdx)

Everything else is exactly as in ../ifpri/build_condensed_sam.py and ../ifpri/build_ifpri_inputs.py (same sector
groups, netting rules, margin split, elasticities, Cobb-Douglas-equivalent LES; for home goods IFPRI's own default
data: LESELAS2 = 1, Frisch -1, SHRHOME from output shares, which is exact here because each activity makes one good).
Run:  py validation/ifpri_home/build_home_inputs.py
"""
from __future__ import annotations

import shutil
import sys
from pathlib import Path

import pandas as pd

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
sys.path.insert(0, str(ROOT))
from pystdcge import paths                     # noqa: E402
from pystdcge.sam import SAM                    # noqa: E402

OUT = HERE / "gams_ph"
OUT.mkdir(exist_ok=True)
SRC = ROOT / "validation" / "ifpri" / "gams_ph"     # IFPRI's include files and the altered model files used in V2

GROUPS = {"agri": ["maiz", "rice", "ocer", "puls", "oils", "root", "vege", "sugr", "toba", "cott", "frui", "coff", "ocrp",
                   "catt", "poul", "oliv", "fore", "fish"], "mine": ["mine"], "food": ["food", "beve"], "chem": ["chem"],
          "oman": ["text", "wood", "nmet", "metl", "mach", "oman"], "util": ["elec", "watr"], "cons": ["cons"],
          "trad": ["trad", "tran"], "serv": ["hotl", "comm", "fsrv", "real", "bsrv", "padm", "educ", "heal", "osrv"]}

raw = SAM.load(paths.SAM_2023)                      # NOT moved: activity -> household cells stay
mapping = {p + m: p + g for g, ms in GROUPS.items() for m in ms for p in "ac" if p + m in raw.codes}
small = raw.aggregate(mapping)
assert small.check(verbose=False)["balanced"]
sam = small.table
codes = list(sam.index)
A = [c for c in codes if c.startswith("a")]
C = [c for c in codes if c.startswith("c")]
F = ["flab-n", "flab-p", "flab-s", "flnd", "fcap"]
H = [c for c in codes if c.startswith("hhd")]
INSD = ["ent"] + H + ["gov"]
INSDNG = ["ent"] + H

# ---- IFPRI's netting rules, as in ../ifpri/build_ifpri_inputs.py
t = sam.copy()
for i in INSD:
    t.loc[i, "row"] -= t.loc["row", i]; t.loc["row", i] = 0.0
for f in F:
    t.loc["row", f] -= t.loc[f, "row"]; t.loc[f, "row"] = 0.0
for i in INSDNG:
    t.loc[i, "gov"] -= t.loc["gov", i]; t.loc["gov", i] = 0.0
for k in codes:
    t.loc[k, k] = 0.0
assert (t.sum(axis=1) - t.sum(axis=0)).abs().max() < 1e-6
t.to_csv(OUT / "sam_netted_home.csv")
home = t.loc[A, H]
print(f"Home consumption kept: {home.values.sum():.1f} bn in {int((home > 0).values.sum())} activity-household cells "
      f"({', '.join(f'{a} {v:.1f}' for a, v in home.sum(axis=1).items() if v > 0)})")

# ---- IFPRI layout: domestic and import margin accounts (marketed domestic sales = SAM(a,c) - exports)
s = t.copy()
out_val = s.loc[A, C].sum()
dom = (out_val - s.loc[C, "row"]).clip(lower=0)
imp = s.loc["row", C]
share_d = (dom / (dom + imp)).fillna(1.0)
s["trcdom"] = 0.0; s["trcimp"] = 0.0
s.loc["trcdom"] = 0.0; s.loc["trcimp"] = 0.0
s.loc["trcdom", C] = s.loc["trc", C] * share_d
s.loc["trcimp", C] = s.loc["trc", C] * (1 - share_d)
supp = s.loc[C, "trc"]
s.loc[C, "trcdom"] = supp * s.loc["trcdom", C].sum() / supp.sum()
s.loc[C, "trcimp"] = supp * s.loc["trcimp", C].sum() / supp.sum()
s = s.drop(index="trc", columns="trc")
assert (s.sum(axis=1) - s.sum(axis=0)).abs().max() < 1e-6
AC = list(s.index)

pop = pd.read_csv(ROOT / "data" / "raw" / "sam" / "003_IFPRI_SAM_PHL_2023_POP.csv", encoding="utf-8-sig", skiprows=1)
pop.columns = ["name", "code", "num", "shr"][: len(pop.columns)]
popmap = {}
for _, r in pop.iterrows():
    c = str(r["code"]).lower()
    for a, full in (("r", "rur"), ("u", "urb")):
        for qq in range(1, 6):
            if c in (f"h_{full}{qq}", f"hhd-{a}{qq}"):
                popmap[f"hhd-{a}{qq}"] = float(str(r["num"]).replace(",", ""))
assert len(popmap) == 10

IFPRI_LABELS = ['instax', 'factax', 'imptax', 'exptax', 'vatax', 'acttax', 'comtax', 'trncstdom', 'trncstexp', 'trncstimp', 'dum']
q = lambda x: "'" + x + "'"
L = lambda xs: ", ".join(q(x) for x in xs)
lines = ["$ontext", "Philippine data for IFPRI's model, HOME CONSUMPTION KEPT (pystdcge validation, 0.3.1). Generated by",
         "validation/ifpri_home/build_home_inputs.py. Condensed IFPRI 2023 Philippine SAM (9 sectors, 10 households), IFPRI netting.", "$offtext",
         "$onempty",
         f"SET AC / {L(AC + IFPRI_LABELS + ['total'])} /;",
         f"SET A(AC) / {L(A)} /;", f"SET AAG(AC) / {L(A)} /;", f"SET C(AC) / {L(C)} /;",
         f"SET MAPAAGA(AAG,A) / {', '.join(q(a) + '.' + q(a) for a in A)} /;",
         f"SET MAPA2C(A,C) / {', '.join(q(a) + '.' + q('c' + a[1:]) for a in A)} /;",
         "SET AAGR(A) / 'aagri' /; SET AMIN(A) / 'amine' /;",
         "SET AIND(A) / 'afood', 'aoman', 'achem', 'autil', 'acons' /; SET ASER(A) / 'atrad', 'aserv' /;",
         "SET CAGR(C) / 'cagri' /; SET CMIN(C) / 'cmine' /;",
         "SET CIND(C) / 'cfood', 'coman', 'cchem', 'cutil', 'ccons' /; SET CSER(C) / 'ctrad', 'cserv' /;",
         f"SET F(AC) / {L(F)} /; SET FAGG(F) / /; SET FLAB(F) / 'flab-n', 'flab-p', 'flab-s' /;",
         "SET FCAP(F) / 'fcap' /; SET FLND(F) / 'flnd' /;",
         f"SET INS(AC) / {L(INSD + ['row'])} /; SET INSD(AC) / {L(INSD)} /; SET INSDNG(AC) / {L(INSDNG)} /;",
         "SET EN(AC) / 'ent' /;", f"SET H(AC) / {L(H)} /;",
         f"SET HURB(AC) / {L([h for h in H if '-u' in h])} /; SET HRUR(AC) / {L([h for h in H if '-r' in h])} /;",
         "SET CTD(AC) / 'trcdom' /; SET CTE(AC) / /; SET CTM(AC) / 'trcimp' /;",
         "SET R(AC) / 'row' /;", "SET GOVF / 'gfun' /;",
         "SET TRDELAS / SIGMAQ, SIGMAT, REGIMP, REGEXP /; SET PRDELAS / PRODELAS, PRODELAS2 /;",
         "PARAMETER NEST(F,F) / /;",
         "PARAMETER SAM(AC,AC) /"]
for i in AC:
    for j in AC:
        v = float(s.loc[i, j])
        if abs(v) > 1e-12:
            lines.append(f"  {q(i)}.{q(j)} {v:.10g}")
lines += ["/;",
          "PARAMETER TRADELAS(AC,TRDELAS) / " + ", ".join(f"{q(c)}.SIGMAQ 2.0, {q(c)}.SIGMAT 2.0" for c in C) + " /;",
          "PARAMETER PRODELASTAB(A,PRDELAS) / " + ", ".join(f"{q(a)}.PRODELAS 0.8, {q(a)}.PRODELAS2 0.6" for a in A) + " /;",
          "PARAMETER LESELAS1(H,C) / " + ", ".join(f"{q(h)}.{q(c)} 1" for h in H for c in C if s.loc[c, h] > 0) + " /;",
          "PARAMETER QFINPUT(F,AAG) / /; PARAMETER WFINPUT(F,AAG) / /;",
          "PARAMETER REGIMP(C,R) / " + ", ".join(f"{q(c)}.'row' 100" for c in C) + " /;",
          "PARAMETER REGTAR(C,R) / " + ", ".join(f"{q(c)}.'row' 100" for c in C) + " /;",
          "PARAMETER REGEXP(C,R) / " + ", ".join(f"{q(c)}.'row' 100" for c in C) + " /;",
          "PARAMETER REGETX(C,R) / " + ", ".join(f"{q(c)}.'row' 100" for c in C) + " /;",
          "PARAMETER POPTAB(AC,*) / " + ", ".join(f"{q(h)}.SURVEY {popmap[h]:.6g}" for h in H) + " /;",
          "PARAMETER GOVFSHR2(GOVF,*) / 'gfun'.'GOV' 1 /;",
          "execute_unload 'ph.gdx';"]
(OUT / "ph_data.gms").write_text("\n".join(lines) + "\n", encoding="utf-8")

# ---- IFPRI's include files and the altered data file (unchanged from V2); the model file gets a home-aware report
for f in ("1diagnostics.inc", "1varinit.inc", "1varlow.inc", "1repbase.inc", "1MODEL_PH.DAT"):
    shutil.copy(SRC / f, OUT / f)
gms = (SRC / "1DMODEL_PH.GMS").read_text(encoding="utf-8", errors="replace")
old_hdr = "(2) a validation block is APPENDED at the end"
assert old_hdr in gms
gms = gms.replace(old_hdr, "(2) a validation block is APPENDED at the end; (3) 8 Oct 2026, home-consumption run: the report\n"
                  "adds home consumption (QHA at base producer prices) to real GDP and consumption and reports it separately")
REP = [("RGDPV = SUM((C,H), PQ0(C)*QH.L(C,H))",
        "RGDPV = SUM((A,C,H), PXAC0(A,C)*QHA.L(A,C,H)) + SUM((C,H), PQ0(C)*QH.L(C,H))"),
       ("RES(CLS,SHK,'MACRO','RCONS') = SUM((C,H), PQ0(C)*QH.L(C,H));",
        "RES(CLS,SHK,'MACRO','RCONS') = SUM((C,H), PQ0(C)*QH.L(C,H)) + SUM((A,C,H), PXAC0(A,C)*QHA.L(A,C,H));\n"
        "    RES(CLS,SHK,'MACRO','RHOME') = SUM((A,C,H), PXAC0(A,C)*QHA.L(A,C,H));"),
       ("RES(CLS,SHK,'RCONSH',H) = SUM(C, PQ0(C)*QH.L(C,H));",
        "RES(CLS,SHK,'RCONSH',H) = SUM(C, PQ0(C)*QH.L(C,H)) + SUM((A,C), PXAC0(A,C)*QHA.L(A,C,H));"),
       ("  PUT CLS.TL, SHK.TL, 'MACRO', 'EXR', RES(CLS,SHK,'MACRO','EXR') /;",
        "  PUT CLS.TL, SHK.TL, 'MACRO', 'EXR', RES(CLS,SHK,'MACRO','EXR') /;\n"
        "  PUT CLS.TL, SHK.TL, 'MACRO', 'RHOME', RES(CLS,SHK,'MACRO','RHOME') /;")]
for a, b in REP:
    assert gms.count(a) == 1, a
    gms = gms.replace(a, b)
(OUT / "1DMODEL_PH.GMS").write_text(gms, encoding="utf-8")
print("Wrote", OUT / "ph_data.gms", "and sam_netted_home.csv; model file with home-aware report;", len(AC), "accounts")
